console.log("4" + 4);
// String + anything -> string concatenation for the + operator.

console.log(Number("4") - 2); // 2
console.log(Number("4") * 2); // 8
console.log(Number("4") / 2); // 2

// In JavaScript, -, *, and / try to convert strings to numbers.
// TypeScript requires the conversion to be explicit for type-safe code.
