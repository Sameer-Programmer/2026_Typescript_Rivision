console.log("4"+4);
//String + anything → String concatenation (for the + operator).

console.log("4" - 2); // 2
console.log("4" * 2); // 8
console.log("4" / 2); // 2

//Because -, *, and / try to convert the string to a number.
/*
Easy interview rule 🧠
+ can concatenate strings.
-, *, /, % perform numeric conversion when possible.
*/